package com.wedding.member04_booking.service;

import com.wedding.member04_booking.model.Booking;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/** Small single-page PDF receipt generator without third-party dependencies. */
public final class BookingPdfReceipt {
    private BookingPdfReceipt() {}
    private static String pdfText(String value) {
        if (value == null) return "";
        StringBuilder s = new StringBuilder();
        for (char c : value.toCharArray()) {
            if (c == '\\' || c == '(' || c == ')') s.append('\\');
            s.append(c >= 32 && c <= 126 ? c : (c == '\n' ? ' ' : '?'));
        }
        return s.toString();
    }
    private static String line(String text, int x, int y, int size, boolean bold) {
        return "BT /" + (bold ? "F2" : "F1") + " " + size + " Tf 1 0 0 1 " + x + " " + y
                + " Tm (" + pdfText(text) + ") Tj ET\n";
    }
    private static List<String> wrap(String value, int max) {
        String clean = (value == null ? "" : value).replaceAll("[\\r\\n|]+", " ").trim();
        List<String> lines = new ArrayList<>();
        StringBuilder current = new StringBuilder();
        for (String word : clean.split("\\s+")) {
            while (word.length() > max) {
                if (current.length() > 0) { lines.add(current.toString()); current.setLength(0); }
                lines.add(word.substring(0, max)); word = word.substring(max);
            }
            if (current.length() + word.length() + 1 > max) {
                lines.add(current.toString()); current.setLength(0);
            }
            if (!word.isEmpty()) { if (current.length() > 0) current.append(' '); current.append(word); }
        }
        if (current.length() > 0) lines.add(current.toString());
        return lines;
    }
    public static byte[] generate(Booking b, String customerName, String vendorName, String planName) {
        StringBuilder content = new StringBuilder();
        content.append("0.93 0.84 0.71 rg 0 745 595 97 re f\n");
        content.append("0.27 0.20 0.14 rg\n").append(line("ECLAT  |  WEDDING PLANNING", 46, 797, 18, true))
            .append(line("BOOKING CONFIRMATION RECEIPT", 46, 772, 11, false));
        content.append("0.25 0.19 0.14 rg\n");
        int y = 710;
        String[][] details = {
            {"BOOKING REFERENCE", b.getBookingId()}, {"STATUS", b.getStatus().getDisplayName()},
            {"CUSTOMER", customerName}, {"VENDOR", vendorName}, {"WEDDING PLAN", planName},
            {"EVENT DATE", b.getBookingDate()}, {"REQUESTED AT", b.getRequestedAt()},
            {"CONFIRMED AT", b.getConfirmedAt() == null ? "-" : b.getConfirmedAt()},
            {"SERVICE FEE", "LKR " + b.getAgreedAmount().toPlainString()}
        };
        for (String[] detail : details) {
            content.append(line(detail[0], 47, y, 9, true));
            content.append(line(detail[1], 220, y, 11, false));
            y -= 40;
        }
        y -= 8;
        content.append("0.79 0.66 0.42 RG 45 ").append(y + 12).append(" m 548 ").append(y + 12).append(" l S\n");
        content.append(line("SERVICE DETAILS", 47, y - 15, 10, true));
        y -= 38;
        for (String s : wrap(b.getServiceDetails(), 90)) {
            if (y < 90) break;
            content.append(line(s, 47, y, 10, false)); y -= 16;
        }
        if (b.getNotes() != null && !b.getNotes().isBlank() && y > 115) {
            y -= 15;
            content.append(line("CUSTOMER NOTES", 47, y, 10, true)); y -= 20;
            for (String s : wrap(b.getNotes(), 90)) {
                if (y < 90) break;
                content.append(line(s, 47, y, 10, false)); y -= 16;
            }
        }
        content.append("0.47 0.37 0.27 rg\n");
        content.append(line("Generated by Eclat Booking Management  |  Keep this receipt for your records.", 47, 52, 9, false));
        byte[] stream = content.toString().getBytes(StandardCharsets.US_ASCII);
        String[] objects = {
            "<< /Type /Catalog /Pages 2 0 R >>",
            "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
            "<< /Length " + stream.length + " >>\nstream\n" + content + "endstream"
        };
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        try {
            out.write("%PDF-1.4\n".getBytes(StandardCharsets.US_ASCII));
            List<Integer> offsets = new ArrayList<>(); offsets.add(0);
            for (int i = 0; i < objects.length; i++) {
                offsets.add(out.size());
                out.write((i+1 + " 0 obj\n" + objects[i] + "\nendobj\n").getBytes(StandardCharsets.US_ASCII));
            }
            int xref = out.size();
            out.write(("xref\n0 " + (objects.length+1) + "\n0000000000 65535 f \n").getBytes(StandardCharsets.US_ASCII));
            for (int i=1; i < offsets.size(); i++) out.write(String.format("%010d 00000 n \n", offsets.get(i)).getBytes(StandardCharsets.US_ASCII));
            out.write(("trailer\n<< /Size " + (objects.length+1) + " /Root 1 0 R >>\nstartxref\n" + xref + "\n%%EOF\n").getBytes(StandardCharsets.US_ASCII));
        } catch (IOException e) { throw new IllegalStateException(e); }
        return out.toByteArray();
    }
}
